/*
 * Personen, deren Porträt zur Laufzeit aus der Wikipedia geladen wird (freie Lizenzen,
 * deshalb liegen keine Bilder in der App). Personen ohne Artikelbild werden übersprungen.
 *
 * Kürzel Bereich: A Film & Schauspiel, M Musik, T TV & Comedy, S Sport, P Politik & Gesellschaft,
 * W Wissenschaft & Wirtschaft, K Kunst & Literatur, F Mode & Models, H Geschichte.
 * Jahrzehnte: 50 (= 50er & früher), 60, 70, 80, 90, 00, 10, 20.
 * Herkunft: DE = deutschsprachig, INT = international.
 */

private const val DE = true
private const val INT = false

private val AREA_CODES = mapOf(
    'A' to Area.ACTING, 'M' to Area.MUSIC, 'T' to Area.TV, 'S' to Area.SPORT, 'P' to Area.POLITICS,
    'W' to Area.SCIENCE, 'K' to Area.ARTS, 'F' to Area.FASHION, 'H' to Area.HISTORY,
)

private val DECADE_CODES = mapOf(
    "50" to Decade.D1950, "60" to Decade.D1960, "70" to Decade.D1970, "80" to Decade.D1980,
    "90" to Decade.D1990, "00" to Decade.D2000, "10" to Decade.D2010, "20" to Decade.D2020,
)

private fun p(first: String, last: String, areas: String, decades: String, german: Boolean, title: String? = null) = Celebrity(
    firstName = first,
    lastName = last,
    wikiTitle = title ?: "$first $last",
    areas = areas.split(' ').map { AREA_CODES.getValue(it.single()) }.toSet(),
    decades = decades.split(' ').map { DECADE_CODES.getValue(it) }.toSet(),
    origin = if (german) Origin.GERMAN else Origin.INTERNATIONAL,
)

